"""mock_clips.py — Synthetic mock-clip generator and PNG screenshot marker utilities for blindpanel.

Enforces Rule 4 & Rule 5:
- Screenshots in the public repository come ONLY from synthetic mock clips generated by `blindpanel.mock_clips`.
- Every screenshot under `docs/` must carry the mock-clip generator marker in its PNG metadata (`tEXt` chunk
  `blindpanel-source: blindpanel-mock-clip-generator-v1`) AND be listed in `docs/screenshots/mock_manifest.json`.
"""
from __future__ import annotations

import hashlib
import json
import shutil
import struct
import subprocess
import zlib
from pathlib import Path
from typing import Dict, List, Optional

MOCK_CLIP_MARKER = "blindpanel-mock-clip-generator-v1"
PNG_SIG = b"\x89PNG\r\n\x1a\n"


def generate_mock_mp4_clip(
    dest_path: str | Path,
    label: str = "MOCK",
    width: int = 832,
    height: int = 480,
    fps: int = 24,
    seconds: float = 1.0,
    color_hex: str = "3b4252",
) -> Dict[str, str]:
    """Generate a synthetic 832x480 H.264 MP4 clip with a moving test bar (or deterministic fallback bytes)
    carrying the `blindpanel-mock-clip-generator-v1` marker."""
    dest = Path(dest_path)
    dest.parent.mkdir(parents=True, exist_ok=True)

    if shutil.which("ffmpeg"):
        # Render synthetic test pattern (no real study content)
        filter_str = f"testsrc=s={width}x{height}:r={fps}:d={seconds}"
        subprocess.run(
            [
                "ffmpeg",
                "-y",
                "-f",
                "lavfi",
                "-i",
                filter_str,
                "-metadata",
                f"comment={MOCK_CLIP_MARKER}:{label}",
                "-c:v",
                "libx264",
                "-pix_fmt",
                "yuv420p",
                str(dest),
            ],
            check=True,
            capture_output=True,
        )
    else:
        payload = f"{MOCK_CLIP_MARKER}:{label}:{width}x{height}".encode("utf-8")
        dest.write_bytes(payload)

    digest = hashlib.sha256(dest.read_bytes()).hexdigest()
    return {
        "path": str(dest),
        "sha256": digest,
        "generator": MOCK_CLIP_MARKER,
    }


def generate_mock_study_clips(
    clips_dir: str | Path,
    arms: List[str],
    base_cells: List[str],
    width: int = 832,
    height: int = 480,
) -> Dict[str, Dict[str, Dict[str, str]]]:
    """Generate a complete set of synthetic mock MP4 clips for a list of arms and cells."""
    cdir = Path(clips_dir)
    cdir.mkdir(parents=True, exist_ok=True)
    palette = ["2e3440", "3b4252", "434c5e", "4c566a"]
    out: Dict[str, Dict[str, Dict[str, str]]] = {}

    # Encode one template MP4 per arm color and stamp unique mock comment trailer per cell for speed & distinct sha256
    templates_by_arm: Dict[str, bytes] = {}
    for a_idx, arm in enumerate(arms):
        color = palette[a_idx % len(palette)]
        tmp_path = cdir / f"_template_{a_idx}.mp4"
        generate_mock_mp4_clip(
            tmp_path,
            label=f"TEMPLATE-{arm}",
            width=width,
            height=height,
            seconds=0.5,
            color_hex=color,
        )
        templates_by_arm[arm] = tmp_path.read_bytes()
        tmp_path.unlink(missing_ok=True)

    for _c_idx, cid in enumerate(base_cells):
        out[cid] = {}
        for _a_idx, arm in enumerate(arms):
            fname = f"{arm}_{cid}.mp4"
            fpath = cdir / fname
            base_bytes = templates_by_arm[arm]
            # Append a deterministic UUID/free atom comment footer so every (arm, cell) has a distinct SHA-256
            footer = f"\n{MOCK_CLIP_MARKER}:{arm}:{cid}".encode("utf-8")
            full_bytes = base_bytes + footer
            fpath.write_bytes(full_bytes)
            out[cid][arm] = {
                "path": str(fpath),
                "sha256": hashlib.sha256(full_bytes).hexdigest(),
                "generator": MOCK_CLIP_MARKER,
            }
    return out


def stamp_png_with_mock_marker(
    png_path: str | Path,
    marker: str = MOCK_CLIP_MARKER,
) -> str:
    """Embed a PNG `tEXt` metadata chunk (`blindpanel-source: blindpanel-mock-clip-generator-v1`)
    immediately before `IEND` and return the resulting file's SHA-256 hex digest."""
    path = Path(png_path)
    raw = path.read_bytes()
    if not raw.startswith(PNG_SIG):
        raise ValueError(f"Not a valid PNG file: {path}")

    # Strip any existing blindpanel-source tEXt chunk to make stamping idempotent
    pos = len(PNG_SIG)
    kept_chunks: List[bytes] = []
    while pos + 8 <= len(raw):
        length = struct.unpack(">I", raw[pos : pos + 4])[0]
        ctype = raw[pos + 4 : pos + 8]
        chunk_end = pos + 8 + length + 4
        chunk_bytes = raw[pos:chunk_end]
        data = raw[pos + 8 : pos + 8 + length]
        if ctype == b"tEXt" and data.startswith(b"blindpanel-source\x00"):
            pos = chunk_end
            continue
        if ctype == b"IEND":
            # Insert fresh tEXt chunk right before IEND
            text_payload = b"blindpanel-source\x00" + marker.encode("utf-8")
            crc = zlib.crc32(b"tEXt" + text_payload) & 0xFFFFFFFF
            text_chunk = (
                struct.pack(">I", len(text_payload))
                + b"tEXt"
                + text_payload
                + struct.pack(">I", crc)
            )
            kept_chunks.append(text_chunk)
        kept_chunks.append(chunk_bytes)
        pos = chunk_end

    stamped = PNG_SIG + b"".join(kept_chunks)
    path.write_bytes(stamped)
    return hashlib.sha256(stamped).hexdigest()


def read_png_mock_marker(png_path: str | Path) -> Optional[str]:
    """Read the `blindpanel-source` `tEXt` metadata chunk from a PNG file if present."""
    path = Path(png_path)
    if not path.is_file():
        return None
    raw = path.read_bytes()
    if not raw.startswith(PNG_SIG):
        return None
    pos = len(PNG_SIG)
    while pos + 8 <= len(raw):
        length = struct.unpack(">I", raw[pos : pos + 4])[0]
        ctype = raw[pos + 4 : pos + 8]
        data = raw[pos + 8 : pos + 8 + length]
        if ctype == b"tEXt" and data.startswith(b"blindpanel-source\x00"):
            return data.split(b"\x00", 1)[1].decode("utf-8", errors="replace")
        pos += 12 + length
    return None


def write_mock_screenshots_manifest(screenshots_dir: str | Path, filenames: List[str]) -> Path:
    """Write `mock_manifest.json` recording the mock-clip generator marker and SHA-256 for each screenshot."""
    sdir = Path(screenshots_dir)
    entries = {}
    for fname in sorted(filenames):
        fpath = sdir / fname
        sha = hashlib.sha256(fpath.read_bytes()).hexdigest()
        entries[fname] = {
            "source_generator": MOCK_CLIP_MARKER,
            "sha256": sha,
        }
    manifest_path = sdir / "mock_manifest.json"
    manifest_path.write_text(
        json.dumps(
            {
                "generator": MOCK_CLIP_MARKER,
                "screenshots": entries,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    return manifest_path
